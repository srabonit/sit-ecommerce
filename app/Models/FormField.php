<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

class FormField extends Model
{
    use HasFactory;

    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | Basic
        |--------------------------------------------------------------------------
        */

        'form_id',
        'type',
        'label',
        'name',
        'placeholder',
        'default_value',
        'help_text',

        /*
        |--------------------------------------------------------------------------
        | Options
        |--------------------------------------------------------------------------
        */

        'options',

        /*
        |--------------------------------------------------------------------------
        | CSS
        |--------------------------------------------------------------------------
        */

        'css_class',
        'wrapper_class',
        'column_width',

        /*
        |--------------------------------------------------------------------------
        | Ordering
        |--------------------------------------------------------------------------
        */

        'sort_order',

        /*
        |--------------------------------------------------------------------------
        | Status
        |--------------------------------------------------------------------------
        */

        'is_required',
        'is_active',

        /*
        |--------------------------------------------------------------------------
        | Validation
        |--------------------------------------------------------------------------
        */

        'min_length',
        'max_length',
        'min_value',
        'max_value',

        /*
        |--------------------------------------------------------------------------
        | File Security
        |--------------------------------------------------------------------------
        */

        'file_max_size',
        'file_max_files',
        'file_allowed_mimes',
        'file_allowed_extensions',
    ];

    protected $casts = [

        /*
        |--------------------------------------------------------------------------
        | JSON
        |--------------------------------------------------------------------------
        */

        'options' => 'array',

        /*
        |--------------------------------------------------------------------------
        | Boolean
        |--------------------------------------------------------------------------
        */

        'is_required' => 'boolean',
        'is_active' => 'boolean',

        /*
        |--------------------------------------------------------------------------
        | Integer
        |--------------------------------------------------------------------------
        */

        'column_width' => 'integer',
        'sort_order' => 'integer',

        'min_length' => 'integer',
        'max_length' => 'integer',

        'min_value' => 'decimal:2',
        'max_value' => 'decimal:2',

        /*
        |--------------------------------------------------------------------------
        | File
        |--------------------------------------------------------------------------
        */

        'file_max_size' => 'integer',
        'file_max_files' => 'integer',
    ];

    /*
    |--------------------------------------------------------------------------
    | Form
    |--------------------------------------------------------------------------
    */

    public function form()
    {
        return $this->belongsTo(
            Form::class,
            'form_id'
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Submission Values
    |--------------------------------------------------------------------------
    */

    public function submissionValues()
    {
        return $this->hasMany(
            FormSubmissionValue::class,
            'field_id'
        );
    }
}